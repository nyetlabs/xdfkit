	$fb = str_starts_with($b[3][0], 'ME') ? 1 : 0;
	if ($fa !== $fb) {
		return $fa <=> $fb;
	}
	$ya = yearStart($a[3][4]);
	$yb = yearStart($b[3][4]);
	if ($ya !== $yb) {
		return $ya <=> $yb;
	}
	$c = strcmp($a[3][4], $b[3][4]);
	if ($c !== 0) {
		return $c;
	}
	$c = strcmp($a[3][3], $b[3][3]);
	return $c !== 0 ? $c : strcmp($a[1], $b[1]);
});
